const assert=require('node:assert/strict');
require('../inspeciona-civil/case-model.js');
const M=globalThis.ICCase;
const legacy={id:'same-id',name:'Caso - reconhecimento exploratório',eligibleUnits:'224 apartamentos totais; universo elegível ainda não definido',notes:'Preservar observação',customField:'preservar'};
const normalized=M.normalize(legacy);
assert.equal(normalized.id,legacy.id);
assert.equal(normalized.eligibleUnits,'');
assert.equal(normalized.eligibleUnitsLegacy,legacy.eligibleUnits);
assert.equal(normalized.totalUnits,'');
assert.equal(normalized.notes,legacy.notes);
assert.equal(normalized.customField,'preservar');
assert.equal(legacy.eligibleUnits.includes('224'),true);
assert.equal(normalized.caseMode,'exploratory');
assert.equal(M.mode({...legacy,caseMode:'research'}),'research');
assert.equal(M.mode({name:'Coleta',notes:'Consulta ao reconhecimento exploratório anterior'}),'research');
assert.equal(M.mode({name:'Piloto do instrumento'}),'pilot');
assert.equal(M.normalize({eligibleUnits:'0'}).eligibleUnits,0);
assert.equal(M.normalize({eligibleUnits:'12'}).eligibleUnits,12);
assert.equal(M.validateCounts({totalUnits:224,eligibleUnits:12}),'');
assert.equal(M.validateCounts({totalUnits:'',eligibleUnits:''}),'');
assert.notEqual(M.validateCounts({totalUnits:12,eligibleUnits:224}),'');
assert.notEqual(M.validateCounts({totalUnits:10,eligibleUnits:-1}),'');
assert.notEqual(M.validateCounts({totalUnits:'2.5',eligibleUnits:1}),'');
assert.equal(M.nextPhotoCode({code:'EXP01'},[{photoCode:'EXP01-F049'},{occurrenceId:'occ',photoCode:'EXP01-FG999'}]),'EXP01-F050');
console.log('PASS: legacy text, stable identity, counts, research mode and independent photo numbering');
